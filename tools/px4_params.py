"""PX4 (v1.15+) control-allocation parameters for the E8-S, generated from the design.

    python tools/px4_params.py  -> firmware/px4/e8s_airframe.params

Body frame FRD (x forward, y right, z down) relative to the CG.  Lift rotors 0-7,
pusher = rotor 8.  CA_ROTORn_KM > 0 means counter-clockwise seen from above.
Values that must be tuned in flight are marked in firmware/README.md.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEL = json.loads((ROOT / "design" / "selected_design.json").read_text())
FEA = json.loads((ROOT / "analysis" / "fea" / "airframe" / "results.json").read_text())


def main():
    g = SEL["geometry"]
    hv = SEL["mission"]["hover"]
    rows = [("CA_AIRFRAME", 2, "Standard VTOL"), ("CA_ROTOR_COUNT", 9, "8 lift + 1 pusher")]
    km = round(hv["torque_nm"] / hv["thrust_per_rotor_n"], 4)
    z_cg = json.loads((ROOT / "cad" / "mass_properties.json").read_text())["cg_mm"][2] / 1000  # CAD CG height
    z_prop = -(0.0365 + 0.036 - z_cg)  # prop plane above the CG (FRD z is down)
    for i, r in enumerate(SEL["layout"]):
        rows += [(f"CA_ROTOR{i}_PX", round(-r["x"], 3), r["name"]), (f"CA_ROTOR{i}_PY", round(r["y"], 3), ""),
                 (f"CA_ROTOR{i}_PZ", round(z_prop, 3), ""), (f"CA_ROTOR{i}_KM", km if r["spin"] > 0 else -km,
                                                               "CCW" if r["spin"] > 0 else "CW")]
    x_p = -(g["fus_tail"] + 0.02 - g["x_cg_target"])
    rows += [("CA_ROTOR8_PX", round(x_p, 3), "pusher"), ("CA_ROTOR8_PY", 0.0, ""), ("CA_ROTOR8_PZ", 0.02, ""),
             ("CA_ROTOR8_AX", 1.0, "thrust forward"), ("CA_ROTOR8_AY", 0.0, ""), ("CA_ROTOR8_AZ", 0.0, ""),
             ("CA_ROTOR8_KM", 0.0, "pusher torque handled by ailerons")]
    rows += [("CA_SV_CS_COUNT", 5, ""), ("CA_SV_CS0_TYPE", 1, "left aileron"), ("CA_SV_CS1_TYPE", 2, "right aileron"),
             ("CA_SV_CS2_TYPE", 3, "elevator"), ("CA_SV_CS3_TYPE", 4, "rudder"), ("CA_SV_CS4_TYPE", 4, "rudder")]
    f1 = FEA["modes"]["modes"][0]["f_hz"]
    rows += [("IMU_GYRO_NF0_FRQ", round(f1, 1), "first airframe mode (FEA); replace with the tap-test value"),
             ("IMU_GYRO_NF0_BW", round(0.3 * f1, 1), ""),
             ("IMU_GYRO_CUTOFF", 30.0, ""), ("VT_TYPE", 2, "standard VTOL"),
             ("VT_ARSP_TRANS", round(1.25 * SEL["stall_ms"], 1), "transition airspeed = 1.25 x stall"),
             ("VT_ARSP_BLEND", round(0.85 * SEL["stall_ms"], 1), ""),
             ("FW_AIRSPD_STALL", round(SEL["stall_ms"], 1), ""), ("FW_AIRSPD_MIN", round(1.2 * SEL["stall_ms"], 1), ""),
             ("FW_AIRSPD_TRIM", round(SEL["mission"]["cruise"]["V"], 1), "design cruise"),
             ("FW_AIRSPD_MAX", round(SEL["max_level_speed_ms"], 1), ""),
             ("MPC_THR_HOVER", round(hv["throttle_frac_thrust"] ** 0.5, 2), "first guess; PX4 learns it"),
             ("BAT1_N_CELLS", 12, ""), ("BAT1_V_EMPTY", 3.5, ""), ("BAT1_V_CHARGED", 4.2, "")]
    out = ROOT / "firmware" / "px4"
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "e8s_airframe.params", "w") as fh:
        fh.write("# E8-S PX4 parameters generated by tools/px4_params.py from design/selected_design.json\n")
        fh.write("# Vehicle-Id\tComponent-Id\tName\tValue\tType\n")
        for name, val, note in rows:
            typ = 6 if isinstance(val, int) else 9
            if note:
                fh.write(f"# {name}: {note}\n")
            fh.write(f"1\t1\t{name}\t{val}\t{typ}\n")
    print(f"{len(rows)} parameters -> {out / 'e8s_airframe.params'}")


if __name__ == "__main__":
    main()
